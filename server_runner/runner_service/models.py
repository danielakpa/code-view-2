"""Database models for persistent runner and sandbox records."""

# Generate timestamps.
from datetime import datetime, timezone

# Generate and validate unique IDs.
from uuid import UUID, uuid4

# Define structured API data.
from pydantic import BaseModel, Field

from sqlalchemy import UniqueConstraint

# SQLAlchemy database column types.
from sqlalchemy import DateTime, Integer, String, Column
from sqlalchemy.dialects.postgresql import UUID as PostgreSQLUUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column



class RunnerSession(BaseModel):
    """Represent a developer session managed by FastAPI."""

    # Unique ID created by Django
    session_id: UUID

    # Developer who owns the session.
    developer_id: int = Field(gt=0)

    # Private group containing the developer.
    group_id: int = Field(gt=0)

    # Current runner lifecycle state.
    status: str = "registered"

    # Time the runner registered this session.
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    # Time the session was last updated.
    updated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )


class Base(DeclarativeBase):
    """Base class used to define SQLAlchemy database tables."""

    pass


class RunnerSessionRecord(Base):
    """Store a runner-managed terminal session in PostgreSQL."""

    # Store the table inside the runner schema.
    __tablename__ = "runner_sessions"
    __table_args__ = {"schema": "runner"}

    # Unique terminal session ID generated by Django.
    session_id: Mapped[UUID] = mapped_column(
        PostgreSQLUUID(as_uuid=True),
        primary_key=True,
    )

    # Developer who owns the terminal session.
    developer_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # Private group containing the developer.
    group_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # Current runner session state.
    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="registered",
    )

    # Time the session was registered.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )

    # Time the session was last updated.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
    )

class SandboxRecord(Base):
    """Store persistent developer sandbox information."""

    # Store the sandbox table inside the runner schema.
    __tablename__ = "sandboxes"

    # Prevent duplicate sandboxes for the same developer and group.
    __table_args__ = (
        UniqueConstraint(
            "developer_id",
            "group_id",
            name="uq_sandbox_developer_group",
        ),
        {"schema": "runner"},
    )

    # Unique sandbox identifier.
    sandbox_id: Mapped[UUID] = mapped_column(
        PostgreSQLUUID(as_uuid=True),
        primary_key=True,
        default=uuid4,
    )

    # Developer who owns the sandbox.
    developer_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # CodeView group associated with the sandbox.
    group_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # Current sandbox lifecycle status.
    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="prepared",
    )

    # Time the sandbox record was created.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )

    # Time the sandbox record was last updated.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
    )

    # Docker container assigned to this sandbox.
    # None means no container has been assigned yet.
    container_id: Mapped[str | None] = mapped_column(
        String(64),
        nullable=True,
        unique=True,
    )

class IDEGrantConsumptionRecord(Base):
    """
    Record IDE authorization grants that have already been used.

    A unique grant ID prevents the same authorization grant
    from being consumed more than once.
    """

    # Store the table inside the Runner's PostgreSQL schema.
    __tablename__ = "ide_grant_consumptions"
    __table_args__ = {"schema": "runner"}

    # STEP 1: Store the unique authorization grant ID.
    # PostgreSQL rejects another record with the same ID.
    grant_id: Mapped[str] = mapped_column(
        String(128),
        primary_key=True,
    )

    # STEP 2: Store the sandbox authorized by this grant.
    sandbox_id: Mapped[UUID] = mapped_column(
        PostgreSQLUUID(as_uuid=True),
        nullable=False,
    )

    # STEP 3: Store the developer who received the grant.
    developer_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # STEP 4: Store the developer's private group.
    group_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # STEP 5: Store when the grant expires.
    expires_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )

    # STEP 6: Record when the grant was consumed.
    consumed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )